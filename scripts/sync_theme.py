"""Regenerate src/dashline/colors.py from the installed Claude Code binary.

Usage: uv run scripts/sync_theme.py [PATH_TO_CLAUDE_BINARY]

Claude Code's built-in themes are plain object literals in its bundle. The function that
maps a theme name to its palette (`switch(r){case"light":return U;...default:return p}`)
names the objects, and each object is `NAME={autoAccept:"...",...,text:"rgb(...)",...}`.
Minified names change every release, so both are found by shape, not by name.
"""

import mmap
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "dashline" / "colors.py"
TOKENS = ("text", "inactive", "subtle", "success", "warning", "error", "fastMode")
BUILTIN = ("dark", "light", "dark-daltonized", "light-daltonized", "dark-ansi", "light-ansi")

SWITCH = re.compile(rb'switch\(\w+\)\{((?:case"[a-z-]+":return [\w$]+;)+)default:return ([\w$]+)\}')
CASE = re.compile(rb'case"([a-z-]+)":return ([\w$]+);')
PAIR = re.compile(rb'(\w+):"([^"]*)"')


def binary_path(argv):
    if len(argv) > 1:
        return Path(argv[1])
    found = shutil.which("claude")
    if not found:
        sys.exit("claude not found on PATH; pass the binary path")
    return Path(found).resolve()


def cli_version(path):
    out = subprocess.run([str(path), "--version"], capture_output=True, text=True, check=True)
    return out.stdout.split()[0]


def find_palettes(data):
    for m in SWITCH.finditer(data):
        names = dict(CASE.findall(m.group(1)))
        if b"light" not in names:
            continue
        names[b"dark"] = m.group(2)
        palettes = {}
        for theme, var in names.items():
            obj = re.search(rb"[,;\s]" + re.escape(var) + rb"=\{autoAccept:[^}]*\}", data)
            if not obj:
                break
            pairs = {k.decode(): v.decode() for k, v in PAIR.findall(obj.group(0))}
            missing = [t for t in TOKENS if t not in pairs]
            if missing:
                sys.exit(
                    f"the {theme.decode()} palette has no {', '.join(missing)}; "
                    "the bundle changed shape"
                )
            palettes[theme.decode()] = {t: pairs[t] for t in TOKENS}
        else:
            return palettes
    sys.exit("couldn't find the theme palettes in this binary; the bundle changed shape")


def render(version, palettes):
    lines = [
        f'"""Claude Code theme tokens, from Claude Code {version}.',
        "",
        "Generated by scripts/sync_theme.py. Do not edit; re-run the script when the CLI",
        "changes its palette. Values are kept in the CLI's own notation (`rgb(r,g,b)` or",
        "`ansi:name`), the same notation custom theme overrides use.",
        '"""',
        "",
        f'CLI_VERSION = "{version}"',
        "",
        "TOKENS = (" + ", ".join(f'"{t}"' for t in TOKENS) + ")",
        "",
        "THEMES = {",
    ]
    for theme in BUILTIN:
        lines.append(f'    "{theme}": {{')
        lines.extend(f'        "{t}": "{palettes[theme][t]}",' for t in TOKENS)
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    path = binary_path(sys.argv)
    with path.open("rb") as f, mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ) as data:
        palettes = find_palettes(data)
    missing = set(BUILTIN) - set(palettes)
    if missing:
        sys.exit(f"palettes missing for {sorted(missing)}")
    OUT.write_text(render(cli_version(path), palettes))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
